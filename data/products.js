/**
 * Helper to get a product's price for a given quantity tier.
 */
export function getPriceForQuantity(product, qty) {
  if (!product?.pricingTiers?.length) return 0;
  const tiers = [...product.pricingTiers].sort((a, b) => b.qty - a.qty);
  for (const tier of tiers) {
    if (qty >= tier.qty) return tier.price;
  }
  return product.pricingTiers[0].price;
}

/**
 * Get the best-value tier for a product.
 */
export function getBestValueTier(product) {
  if (!product?.pricingTiers?.length) return null;
  return product.pricingTiers.reduce((best, tier) =>
    tier.price < best.price ? tier : best
  );
}

/**
 * Calculate savings between two quantity tiers.
 */
export function calculateSavings(product, currentQty, compareQty) {
  const currentPrice = getPriceForQuantity(product, currentQty);
  const comparePrice = getPriceForQuantity(product, compareQty);
  return (comparePrice - currentPrice) * currentQty;
}

/**
 * Get products by category slug.
 */
export function getProductsByCategory(categorySlug) {
  return products.filter((p) => p.category === categorySlug);
}

/**
 * Get a product by slug.
 */
export function getProductBySlug(slug) {
  return products.find((p) => p.slug === slug);
}

/**
 * Get popular products (first 8 corrugated boxes).
 */
export function getPopularProducts() {
  return products.filter((p) => p.category === 'corrugated-boxes').slice(0, 8);
}

